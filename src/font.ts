function bits(rows: string[]): number[] {
  return rows.map((r) => parseInt(r, 2));
}

const FONT: Record<string, number[]> = {};
for (const [k, v] of Object.entries(RAW)) FONT[k] = bits(v);

export function glyphWidth(ch: string): number {
  if (ch === " ") return 3;
  const rows = FONT[ch];
  if (!rows) return 4;
  let max = 1;
  for (const row of rows) {
    for (let x = 0; x < 5; x++) if (row & (1 << (4 - x))) max = Math.max(max, x + 1);
  }
  return max;
}

export function measure(text: string): number {
  let w = 0;
  for (const ch of text) w += glyphWidth(ch) + 1;
  return Math.max(0, w - 1);
}

export function wrap(text: string, maxW: number): string[] {
  const words = text.split(" ");
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (measure(next) > maxW && line) {
      lines.push(line);
      line = word;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}

export function drawText(pix: Pix, text: string, x: number, y: number, color: number): void {
  let cx = x;
  for (const ch of text) {
    const rows = FONT[ch] ?? FONT["?"];
    for (let j = 0; j < rows.length; j++) {
      const row = rows[j];
      for (let i = 0; i < 5; i++) if (row & (1 << (4 - i))) pix.set(cx + i, y + j, color);
    }
    cx += glyphWidth(ch) + 1;
  }
}
